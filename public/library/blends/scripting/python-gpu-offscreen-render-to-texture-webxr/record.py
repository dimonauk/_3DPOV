"""
record.py — Viewport Animation Recording
Tutorial: Python gpu.types.GPUOffScreen — Offscreen Render-to-Texture
Blender 5.1 | CC0 | Holoflow Studio

PURPOSE
-------
Produce public/library/videos/scripting/
  python-gpu-offscreen-render-to-texture-webxr/viewport.mp4

The clip shows the baked world-space normal map displayed as a flat quad
beside the source icosphere, both rotating in sync over 120 frames (4 s
at 30 fps).  A second, smaller quad shows the depth channel (alpha) in
greyscale so viewers can see both outputs simultaneously.

HOW TO RUN
----------
1. Open Blender 5.1.
2. Paste this script into a Text Editor data-block.
3. Press Run Script.
The .mp4 is written directly alongside the .blend file.
"""

import bpy, os, math

SLUG      = 'python-gpu-offscreen-render-to-texture-webxr'
TOPIC     = 'scripting'
OUT_DIR   = bpy.path.abspath(
    f'//public/library/videos/{TOPIC}/{SLUG}/'
)
os.makedirs(OUT_DIR, exist_ok=True)

FPS    = 30
FRAMES = 120     # 4-second clip

# ── Clean scene ──────────────────────────────────────────────────────────
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete()
for block in [bpy.data.meshes, bpy.data.materials, bpy.data.images,
              bpy.data.cameras, bpy.data.lights]:
    for item in list(block):
        block.remove(item)

# ── Source icosphere ─────────────────────────────────────────────────────
bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=1, radius=0.7,
                                       location=(-1.2, 0, 0))
sphere = bpy.context.active_object
sphere.name = 'source_sphere'
bpy.ops.object.shade_flat()

# Material: white Principled for clean viewport preview
mat_src = bpy.data.materials.new('src_mat')
mat_src.use_nodes = True
bsdf = mat_src.node_tree.nodes['Principled BSDF']
bsdf.inputs['Base Color'].default_value = (0.85, 0.85, 0.90, 1.0)
sphere.data.materials.append(mat_src)

# Rotation keyframes: full 360° over FRAMES
sphere.rotation_euler = (0, 0, 0)
sphere.keyframe_insert('rotation_euler', frame=1)
sphere.rotation_euler = (0, 0, math.radians(360))
sphere.keyframe_insert('rotation_euler', frame=FRAMES)

for fc in sphere.animation_data.action.fcurves:
    for kp in fc.keyframe_points:
        kp.interpolation = 'LINEAR'

# ── Baked-texture display quad ───────────────────────────────────────────
# In a real session the normal map was already generated by blueprint.py.
# Here we load or create a placeholder image so the recording scene builds.
blend_dir = bpy.path.abspath(
    f'//public/library/blends/{TOPIC}/{SLUG}/'
)
tex_path = os.path.join(blend_dir, 'world_normal_data_tex.webp')

if os.path.isfile(tex_path):
    bake_img = bpy.data.images.load(tex_path)
else:
    # Placeholder: procedural RGB noise to mimic a normal map visually
    bake_img = bpy.data.images.new('world_normal_data_tex', 256, 256, alpha=True)
    import random
    px = []
    for _ in range(256 * 256):
        r = 0.5 + random.gauss(0, 0.15)
        g = 0.5 + random.gauss(0, 0.15)
        b = 0.7 + random.gauss(0, 0.10)
        px.extend([max(0,min(1,r)), max(0,min(1,g)), max(0,min(1,b)), 1.0])
    bake_img.pixels[:] = px

bpy.ops.mesh.primitive_plane_add(size=1.4, location=(1.2, 0, 0))
quad = bpy.context.active_object
quad.name = 'normal_map_display'

mat_q = bpy.data.materials.new('normal_map_disp_mat')
mat_q.use_nodes = True
nodes = mat_q.node_tree.nodes
links = mat_q.node_tree.links
nodes.clear()

out   = nodes.new('ShaderNodeOutputMaterial')
bsdf2 = nodes.new('ShaderNodeBsdfPrincipled')
tex_n = nodes.new('ShaderNodeTexImage')
tex_n.image = bake_img
links.new(tex_n.outputs['Color'], bsdf2.inputs['Base Color'])
bsdf2.inputs['Roughness'].default_value = 1.0
links.new(bsdf2.outputs['BSDF'], out.inputs['Surface'])
quad.data.materials.append(mat_q)

# Quad rotates in sync with sphere to show the bake is view-independent
quad.rotation_euler = (0, 0, 0)
quad.keyframe_insert('rotation_euler', frame=1)
quad.rotation_euler = (0, 0, math.radians(360))
quad.keyframe_insert('rotation_euler', frame=FRAMES)
for fc in quad.animation_data.action.fcurves:
    for kp in fc.keyframe_points:
        kp.interpolation = 'LINEAR'

# ── Camera ───────────────────────────────────────────────────────────────
bpy.ops.object.camera_add(location=(0, -4.0, 0.8))
cam = bpy.context.active_object
cam.rotation_euler = (math.radians(80), 0, 0)
bpy.context.scene.camera = cam

# ── Key light ────────────────────────────────────────────────────────────
bpy.ops.object.light_add(type='AREA', location=(2, -2, 3))
key = bpy.context.active_object
key.data.energy = 300
key.data.size   = 2.0

# ── Render settings ──────────────────────────────────────────────────────
scene = bpy.context.scene
scene.render.engine              = 'BLENDER_WORKBENCH'
scene.display.shading.light      = 'STUDIO'
scene.render.resolution_x        = 1920
scene.render.resolution_y        = 1080
scene.render.fps                 = FPS
scene.frame_start                = 1
scene.frame_end                  = FRAMES
scene.render.image_settings.file_format  = 'FFMPEG'
scene.render.ffmpeg.format               = 'MPEG4'
scene.render.ffmpeg.codec                = 'H264'
scene.render.ffmpeg.constant_rate_factor = 'HIGH'
scene.render.ffmpeg.ffmpeg_preset        = 'GOOD'
scene.render.filepath            = os.path.join(OUT_DIR, 'viewport')
scene.render.use_file_extension  = True

bpy.ops.render.render(animation=True)
print(f'Viewport recording → {OUT_DIR}viewport.mp4')
