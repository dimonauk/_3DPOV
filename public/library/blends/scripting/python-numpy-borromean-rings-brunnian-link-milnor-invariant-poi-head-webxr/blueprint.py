"""
Borromean Rings: Brunnian Three-Component Link, Milnor μ̄₁₂₃=1 & Oval-Ring Poi Head
====================================================================================
Blender 5.1 · Python 3.12 · numpy — Holoflow Studio · CC0

WHY THIS GEOMETRY EXISTS
------------------------
Three loops are Borromean when: (a) no TWO loops are linked (every pairwise
linking number is zero), yet (b) all THREE together are inseparable — remove any
one ring and the remaining two spring free.  This counter-intuitive arrangement
is characterised by Milnor's triple linking number μ̄₁₂₃ = ±1 (the simplest
Brunnian link invariant beyond pairwise Lk).

Freedman–Skora 1987 proved that ROUND circles in R³ CANNOT realise Borromean
rings.  The fix used here: slight asphericity (oval semi-axes a=1.4, b=1.0).
Under the cyclic symmetry group Z₃ (generated by permuting X→Y→Z), each oval
ring is the image of its predecessor.  Every pair has clearing distance a−b=0.4
at its crossing point, giving a tube-tube gap of 0.16 m at TUBE_R=0.12 — tight
but provably collision-free (verified analytically below).

RING DEFINITIONS (cyclic Z₃ symmetry)
---------------------------------------
  Ring A  XZ plane (y≡0) :  (a·cos t, 0,  b·sin t)
  Ring B  XY plane (z≡0) :  (b·sin t, a·cos t, 0)
  Ring C  YZ plane (x≡0) :  (0, b·cos t, a·sin t)

CROSSING PROOF
  Ring B crosses y=0 at t=π/2 →  (b, 0, 0).
  Point (b,0,0) in Ring A's hole? (b/a)²=0.51 < 1  ✓
  Min path-distance = a−b = 0.4 > 2·TUBE_R = 0.24  ✓
By Z₃ symmetry all six crossings have identical clearance = 0.16 m.
"""

import bpy, bmesh, math, numpy as np
from mathutils import Vector

# ── Parameters ───────────────────────────────────────────────────────────────
A             = 1.40    # major semi-axis (wide axis of each oval ring)
B             = 1.00    # minor semi-axis (narrow axis) — clearance = A−B = 0.40
TUBE_R        = 0.12    # tube cross-section radius; must be < (A−B)/2
N_PATH        = 96      # vertices along ring centre-line (divisible by 4)
N_TUBE        = 18      # vertices around tube cross-section
DELTA         = 0.09    # visual crossing-bump magnitude (< TUBE_R; aesthetic only)
SIGMA         = 0.32    # crossing-zone half-width (radians); smooth Gaussian

COLLECTION    = "borromean_rings"
ROOT_EMPTY    = "hf_borromean_poi"
EXPORT_PATH   = "//hf_borromean_poi.glb"

RING_COLOURS  = [
    (0.88, 0.22, 0.12, 1.0),   # Ring A — vermilion
    (0.18, 0.52, 0.88, 1.0),   # Ring B — cobalt
    (0.20, 0.76, 0.38, 1.0),   # Ring C — malachite
]
RING_METALLIC  = 0.72
RING_ROUGHNESS = 0.22

# ── Helpers ──────────────────────────────────────────────────────────────────

def gauss_bump(t: np.ndarray, centre: float) -> np.ndarray:
    """Smooth crossing bump: Gaussian on the circle [0, 2π)."""
    d = (t - centre + math.pi) % (2 * math.pi) - math.pi   # wrap to (−π, π]
    return np.exp(-0.5 * (d / SIGMA) ** 2)


def ring_path(ring_idx: int) -> np.ndarray:
    """
    Compute (N_PATH, 3) centre-line for one ring.
    Small DELTA bumps are added perpendicular to the ring plane at each crossing
    zone to accentuate the over/under topology (DELTA << TUBE_R so shape is not
    distorted; they are aesthetic amplifiers of the geometry that already clears).

    Cyclic over/under pattern (Borromean convention):
      +x zone : A over B  |  −x zone : B over A
      +z zone : A over C  |  −z zone : C over A
      +y zone : B over C  |  −y zone : C over B
    Each ring's normal is its plane normal: A→Y, B→Z, C→X.
    """
    t = np.linspace(0, 2 * math.pi, N_PATH, endpoint=False)

    if ring_idx == 0:                          # Ring A — XZ plane, normal Y
        pts = np.column_stack([A * np.cos(t), np.zeros(N_PATH), B * np.sin(t)])
        bump_y = (DELTA * gauss_bump(t, 0.0)          # +Y at t=0   (A over B, near +x)
                  - DELTA * gauss_bump(t, math.pi)    # −Y at t=π   (B over A, near −x)
                  + DELTA * gauss_bump(t, math.pi/2)  # +Y at t=π/2 (A over C, near +z)
                  - DELTA * gauss_bump(t, 3*math.pi/2))  # −Y at t=3π/2 (C over A, near −z)
        pts[:, 1] += bump_y

    elif ring_idx == 1:                        # Ring B — XY plane, normal Z
        pts = np.column_stack([B * np.sin(t), A * np.cos(t), np.zeros(N_PATH)])
        # Ring B crosses near (+x) at t=π/2, near (−x) at t=3π/2
        # Ring B crosses near (+y) at t=0,   near (−y) at t=π
        bump_z = (-DELTA * gauss_bump(t, math.pi/2)    # −Z at t=π/2  (A over B)
                  + DELTA * gauss_bump(t, 3*math.pi/2)  # +Z at t=3π/2 (B over A)
                  + DELTA * gauss_bump(t, 0.0)          # +Z at t=0   (B over C, near +y)
                  - DELTA * gauss_bump(t, math.pi))     # −Z at t=π   (C over B, near −y)
        pts[:, 2] += bump_z

    else:                                      # Ring C — YZ plane, normal X
        pts = np.column_stack([np.zeros(N_PATH), B * np.cos(t), A * np.sin(t)])
        # Ring C near (+z) at t=π/2, near (−z) at t=3π/2
        # Ring C near (+y) at t=0,   near (−y) at t=π
        bump_x = (-DELTA * gauss_bump(t, math.pi/2)    # −X at t=π/2  (A over C)
                  + DELTA * gauss_bump(t, 3*math.pi/2)  # +X at t=3π/2 (C over A)
                  - DELTA * gauss_bump(t, 0.0)          # −X at t=0   (B over C)
                  + DELTA * gauss_bump(t, math.pi))     # +X at t=π   (C over B)
        pts[:, 0] += bump_x

    return pts


def bishop_frame(pts: np.ndarray):
    """
    Parallel-transport (Bishop) frame for a closed curve.
    Returns arrays T[N], N[N], Bn[N] each (N,3).
    Distributes residual holonomy linearly to avoid seam twist.
    """
    n = len(pts)
    T = np.zeros((n, 3))
    for i in range(n):
        diff = pts[(i + 1) % n] - pts[(i - 1) % n]
        T[i] = diff / (np.linalg.norm(diff) + 1e-12)

    # Seed normal: arbitrary perpendicular to T[0]
    tx, ty, tz = T[0]
    if abs(tx) < 0.9:
        seed = np.array([1.0, 0.0, 0.0])
    else:
        seed = np.array([0.0, 1.0, 0.0])
    n0 = np.cross(T[0], seed)
    n0 /= np.linalg.norm(n0)

    Nf = np.zeros((n, 3))
    Nf[0] = n0
    for i in range(1, n):
        proj = Nf[i - 1] - np.dot(Nf[i - 1], T[i]) * T[i]
        Nf[i] = proj / (np.linalg.norm(proj) + 1e-12)

    # Holonomy correction: measure closing twist, distribute evenly
    dot_nn = np.clip(np.dot(Nf[-1], Nf[0]), -1.0, 1.0)
    cross_nn = np.cross(Nf[-1], Nf[0])
    holonomy = math.atan2(np.dot(cross_nn, T[0]), dot_nn)
    for i in range(n):
        angle = holonomy * i / n
        c, s = math.cos(angle), math.sin(angle)
        Nf[i] = c * Nf[i] + s * np.cross(T[i], Nf[i])

    Bn = np.array([np.cross(T[i], Nf[i]) for i in range(n)])
    return T, Nf, Bn


def build_tube(bm: bmesh.types.BMesh, pts: np.ndarray) -> None:
    """Sweep a circle of radius TUBE_R along pts, adding quads to bm."""
    n, nt = len(pts), N_TUBE
    _, Nf, Bn = bishop_frame(pts)

    # Build all vertices
    verts = []
    for i in range(n):
        ring = []
        for j in range(nt):
            angle = 2 * math.pi * j / nt
            pos = (pts[i]
                   + TUBE_R * math.cos(angle) * Nf[i]
                   + TUBE_R * math.sin(angle) * Bn[i])
            ring.append(bm.verts.new(Vector(pos.tolist())))
        verts.append(ring)

    bm.verts.ensure_lookup_table()

    # Connect rings with quads, closing the loop
    for i in range(n):
        i_next = (i + 1) % n
        for j in range(nt):
            j_next = (j + 1) % nt
            v0 = verts[i][j]
            v1 = verts[i][j_next]
            v2 = verts[i_next][j_next]
            v3 = verts[i_next][j]
            bm.faces.new([v0, v1, v2, v3])


def make_material(name: str, colour):
    mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = colour
    bsdf.inputs["Metallic"].default_value    = RING_METALLIC
    bsdf.inputs["Roughness"].default_value   = RING_ROUGHNESS
    return mat


# ── Scene Setup ───────────────────────────────────────────────────────────────

bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete()

col = bpy.data.collections.new(COLLECTION)
bpy.context.scene.collection.children.link(col)

root = bpy.data.objects.new(ROOT_EMPTY, None)
col.objects.link(root)
root["holoflow:facet"]    = True
root["holoflow:category"] = "poi-head"

labels = ["ring_a_vermilion", "ring_b_cobalt", "ring_c_malachite"]

for idx in range(3):
    pts  = ring_path(idx)
    bm   = bmesh.new()
    build_tube(bm, pts)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)

    mesh = bpy.data.meshes.new(labels[idx])
    bm.to_mesh(mesh)
    bm.free()

    obj = bpy.data.objects.new(labels[idx], mesh)
    col.objects.link(obj)
    obj.parent = root

    mat = make_material(f"mat_{labels[idx]}", RING_COLOURS[idx])
    obj.data.materials.append(mat)

# ── Export ────────────────────────────────────────────────────────────────────
root.rotation_euler = (math.pi / 2, 0, 0)   # +Y-up for WebXR
bpy.context.view_layer.update()

bpy.ops.object.select_all(action='DESELECT')
for obj in col.objects:
    obj.select_set(True)
bpy.context.view_layer.objects.active = root

bpy.ops.export_scene.gltf(
    filepath=EXPORT_PATH,
    use_selection=True,
    export_draco_mesh_compression_enable=True,
    export_draco_mesh_compression_level=6,
    export_image_format='WEBP',
    export_yup=True,
    export_colors=True,
)

print("✓ Borromean poi exported →", EXPORT_PATH)
