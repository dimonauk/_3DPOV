"""
Apollonian Gasket — Blender 5.1 Blueprint
==========================================
Technique: Apollonius circle packing via Vieta jumping on the Descartes theorem.

The Apollonian gasket is a fractal circle packing generated by the Problem of
Apollonius (c.200 BC): given three mutually tangent circles, find all circles
tangent to all three. René Descartes proved in 1643 that for four mutually
tangent circles with curvatures k=1/r (curvature is negative for the enclosing
outer circle):

    (k₁+k₂+k₃+k₄)² = 2(k₁²+k₂²+k₃²+k₄²)        [Descartes Circle Theorem]

Frederick Soddy rediscovered this in 1936 and published it as a sonnet, "The
Kiss Precise", in Nature. Starting from the integer seed (−1,2,2,3), ALL
descendant curvatures are integers (Apollonius group / Vieta jumping). The
Hausdorff dimension of the residual fractal limit is δ≈1.3057 (Boyd 1973).

Trade-off: flat discs (z=0 at Basis) give a classic "stamp-pad" floor plan.
The SK_Elevated shape key lifts each disc by log(k)/log(MAX_K)·H_SCALE so
small circles peak above large ones — a curvature-landscape view.
"""

# ─── Parameters ───────────────────────────────────────────────────────────────
R0          = 0.80      # outer-circle radius in metres (world space)
MAX_K       = 80        # maximum curvature; minimum disc radius = R0/MAX_K ≈ 10 mm
N_CIRC_MAX  = 32        # angular segments for the largest (k=2) circles
DISC_THICK  = 0.004     # half-thickness for face normals (flat disc, z=±DISC_THICK)
H_SCALE     = 0.120     # height amplitude for shape keys (m)
COBALT      = (0.06, 0.14, 0.66, 1.0)
AMBER       = (0.88, 0.52, 0.04, 1.0)
MESH_NAME   = "Apollonian_Gasket"
OBJ_NAME    = "apollonian_gasket_floor"
BLEND_FILE  = "apollonian_gasket_floor.blend"
GLB_PATH    = "public/library/glbs/scripting/" \
              "python-numpy-apollonian-gasket-descartes-theorem-integer-packing-fractal-stage-floor-webxr/" \
              "apollonian_gasket_floor.glb"

# ─── Imports ──────────────────────────────────────────────────────────────────
import math, cmath
from collections import deque
import numpy as np
import bpy

# ─── Apollonian BFS via Vieta jumping ─────────────────────────────────────────
def generate_gasket(max_k=MAX_K):
    """
    BFS over the Apollonian group starting from the integer seed (−1,2,2,3).

    WHY Vieta jumping (not the ± square-root formula): given a valid Apollonian
    quadruple (k1,k2,k3,k4), Vieta's formulae give the 'sibling' of k4 as:
        k4' = 2(k1+k2+k3) − k4        [integer arithmetic — no sqrt needed!]
        k4'·z4' = 2(k1·z1+k2·z2+k3·z3) − k4·z4    [complex centres]
    This is exact when curvatures are integers, avoiding floating-point branch
    cuts in complex square-roots. The Vieta jump always produces the unique
    OTHER circle tangent to the same triple (A,B,C) as k4.

    Seed positions for (−1,2,2,3) derived from tangency constraints:
      k=−1: z=0 (outer circle, radius 1 unit)
      k=2:  z=±0.5i  (radius 0.5, internally tangent to outer, externally
                       tangent to each other: |z1−z2|=0.5+0.5=1 ✓)
      k=3:  z=2/3    (radius 1/3; |z|=1−1/3=2/3 ✓; |z−(0,±0.5)|=5/6 ✓)
    """
    PREC = 6

    def ckey(k, z):
        return (int(round(k)), round(z.real, PREC), round(z.imag, PREC))

    root = [
        (-1, complex(0, 0)),
        ( 2, complex(0, -0.5)),
        ( 2, complex(0,  0.5)),
        ( 3, complex(2/3, 0)),
    ]

    seen_circles = set()
    circles = []          # (k_int, complex_centre)

    for k, z in root:
        seen_circles.add(ckey(k, z))
        if k > 0:
            circles.append((int(round(k)), z))

    def qkey(quad):
        return frozenset(ckey(k, z) for k, z in quad)

    seen_quads = set()
    queue = deque()
    rq = tuple(root)
    seen_quads.add(qkey(rq))
    queue.append(rq)

    while queue:
        quad = queue.popleft()
        ks  = [q[0] for q in quad]
        czs = [q[1] for q in quad]

        for i in range(4):
            others_k  = [ks[j]  for j in range(4) if j != i]
            others_cz = [czs[j] for j in range(4) if j != i]

            k_new = 2 * sum(others_k) - ks[i]
            if k_new <= 0 or k_new > max_k:
                continue

            kz_sum = sum(ok * oz for ok, oz in zip(others_k, others_cz))
            z_new  = (2 * kz_sum - ks[i] * czs[i]) / k_new

            k_int = int(round(k_new))
            ck = ckey(k_int, z_new)
            if ck not in seen_circles:
                seen_circles.add(ck)
                circles.append((k_int, z_new))

            new_quad = list(quad)
            new_quad[i] = (k_int, z_new)
            new_quad_t = tuple(new_quad)
            qk = qkey(new_quad_t)
            if qk not in seen_quads:
                seen_quads.add(qk)
                queue.append(new_quad_t)

    return circles

# ─── Disc mesh builder ─────────────────────────────────────────────────────────
def n_circ_for_k(k):
    """Angular resolution scales as 1/√k so small circles stay low-poly."""
    return max(6, int(N_CIRC_MAX / math.sqrt(max(1, k / 2.0))))

def build_disc_verts(cx, cy, r, n, z_offset=0.0):
    """
    Flat fan-triangulated disc centred at (cx,cy), radius r, n_circ segments.
    Returns (verts_list, faces_list) with vertex indices local to this disc.
    WHY fan triangulation: simpler index arithmetic than ear-clip; correct for
    convex discs; no interior vertex pinching unlike grid approach.
    """
    verts = [(cx, cy, z_offset)]  # centre vertex at index 0
    angle_step = 2 * math.pi / n
    for j in range(n):
        a = j * angle_step
        verts.append((cx + r * math.cos(a), cy + r * math.sin(a), z_offset))
    faces = [(0, j + 1, (j % n) + 2) for j in range(n)]
    return verts, faces

def disc_colour(k, max_k=MAX_K):
    """
    Cobalt (low k, large circles) → amber (high k, small circles).
    Log-scale so mid-sized circles sit in the gradient, not squashed near 0.
    """
    t = math.log(max(1, k)) / math.log(max(2, max_k))
    t = min(1.0, max(0.0, t))
    return tuple(COBALT[i] * (1 - t) + AMBER[i] * t for i in range(4))

# ─── Main build ───────────────────────────────────────────────────────────────
def build():
    print("Apollonian Gasket: generating circle packing …")
    raw = generate_gasket(MAX_K)
    print(f"  → {len(raw)} circles (k ≤ {MAX_K})")

    # Sort by descending radius (ascending k) so large circles are drawn first
    raw.sort(key=lambda c: c[0])

    # Assemble combined mesh: one fan disc per circle
    all_verts = []
    all_faces = []
    all_colours = []       # per-vertex FLOAT_COLOR for Apollon_K attribute
    sk_elevated = []       # SK_Elevated: z = log(k)/log(MAX_K) * H_SCALE
    sk_inverted = []       # SK_Inverted: z = (1−t) * H_SCALE (large circles high)

    for k, z_c in raw:
        r_world = R0 / k                     # disc radius in metres
        cx = z_c.real * R0
        cy = z_c.imag * R0
        n  = n_circ_for_k(k)
        colour = disc_colour(k)

        base_v, base_f = build_disc_verts(cx, cy, r_world, n, z_offset=0.0)
        offset = len(all_verts)

        all_verts.extend(base_v)
        all_faces.extend([(f[0] + offset, f[1] + offset, f[2] + offset)
                          for f in base_f])
        all_colours.extend([colour] * len(base_v))

        # Shape key verts — same XY, lifted Z
        t_log = math.log(max(1, k)) / math.log(max(2, MAX_K))
        z_elev = t_log * H_SCALE
        z_inv  = (1.0 - t_log) * H_SCALE

        elev_v = [(v[0], v[1], z_elev) for v in base_v]
        inv_v  = [(v[0], v[1], z_inv)  for v in base_v]
        sk_elevated.extend(elev_v)
        sk_inverted.extend(inv_v)

    print(f"  → mesh: {len(all_verts)} verts, {len(all_faces)} tris")

    # ── Create Blender mesh ──
    mesh = bpy.data.meshes.new(MESH_NAME)
    mesh.from_pydata(all_verts, [], all_faces)
    mesh.update()

    # ── Vertex colour attribute ──
    attr = mesh.color_attributes.new(name="Apollon_K",
                                     type="FLOAT_COLOR", domain="POINT")
    flat = [ch for col in all_colours for ch in col]
    attr.data.foreach_set("color", flat)

    # ── Object ──
    for ob in bpy.data.objects:
        if ob.name == OBJ_NAME:
            bpy.data.objects.remove(ob, do_unlink=True)
    obj = bpy.data.objects.new(OBJ_NAME, mesh)
    bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)

    # ── holoflow meta ──
    obj["holoflow:facet"]    = True
    obj["holoflow:category"] = "stage-floor"
    obj["holoflow:topic"]    = "apollonian-gasket"

    # ── Shape keys ──
    sk_basis = obj.shape_key_add(name="Basis", from_mix=False)
    sk_basis.interpolation = "KEY_LINEAR"

    def add_sk(name, co_list):
        sk = obj.shape_key_add(name=name, from_mix=False)
        sk.interpolation = "KEY_LINEAR"
        flat_sk = np.array(co_list, dtype=np.float32).ravel()
        sk.data.foreach_set("co", flat_sk)

    add_sk("SK_Elevated", sk_elevated)
    add_sk("SK_Inverted", sk_inverted)

    # ── Material ──
    mat = bpy.data.materials.new("Apollon_Mat")
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links
    nodes.clear()

    attr_n = nodes.new("ShaderNodeAttribute")
    attr_n.attribute_name = "Apollon_K"
    attr_n.attribute_type = "GEOMETRY"

    bsdf = nodes.new("ShaderNodeBsdfPrincipled")
    bsdf.inputs["Metallic"].default_value = 0.35
    bsdf.inputs["Roughness"].default_value = 0.30
    emission_strength = bsdf.inputs.get("Emission Strength") \
                        or bsdf.inputs.get("Emission")
    if emission_strength:
        emission_strength.default_value = 0.40

    out = nodes.new("ShaderNodeOutputMaterial")
    links.new(attr_n.outputs["Color"], bsdf.inputs["Base Color"])
    links.new(attr_n.outputs["Color"], bsdf.inputs["Emission Color"])
    links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    mesh.materials.append(mat)

    # ── +Y-up transform for WebXR ──
    import mathutils
    obj.rotation_euler = mathutils.Euler((math.pi / 2, 0, 0), "XYZ")
    bpy.ops.object.transform_apply(location=False, rotation=True, scale=False)

    # ── GLB export ──
    import os
    glb_abs = os.path.join(bpy.path.abspath("//"), GLB_PATH)
    os.makedirs(os.path.dirname(glb_abs), exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=glb_abs,
        export_format="GLB",
        export_draco_mesh_compression_enable=True,
        export_draco_mesh_compression_level=6,
        export_image_format="WEBP",
        export_colors=True,
        export_morph=True,
        export_yup=True,
    )
    print(f"Apollonian Gasket: GLB written → {glb_abs}")

build()
