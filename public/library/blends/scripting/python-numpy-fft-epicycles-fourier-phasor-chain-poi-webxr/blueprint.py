"""
Python numpy — FFT Epicycles: Fourier-Series Phasor Chain for Poi Light-Painting
Blender 5.1 · CC0 · Holoflow Studio

Technique:
  A 2D poi figure-eight (Lemniscate of Bernoulli) is sampled as N complex numbers
  z[n] = x[n] + i·y[n]. The DFT (numpy.fft.fft) decomposes the path into N
  rotating circles — one per frequency bin k:

    z[n] = (1/N) · Σ_k  C[k] · e^{2πi·k·n/N}

  Each term is a phasor: a circle of radius |C[k]|/N rotating at angular frequency
  k·2π/N radians per frame. Sorting by descending |C[k]| gives the "most important"
  circles first. A chain of N_CIRCLES parented Empties represents the sum; the tip
  traces the reconstructed path as the empties rotate.

  Key efficiency trick: each Empty needs only TWO linear-interpolated keyframes
  (frame 1 and frame FRAME_END+1) rather than one per frame — constant angular
  velocity means the FCurve is an exact linear ramp.

  The trail is generated by evaluating the depsgraph tip position every frame;
  this gives the exact accumulated world position including all parent rotations.
"""

import bpy, bmesh, math, numpy as np
from mathutils import Vector

# ─── PARAMETERS ──────────────────────────────────────────────────────────────
N_SAMPLES    = 256    # path resolution — power of 2 is fastest for FFT
N_CIRCLES    = 22     # Fourier terms to visualise; 22 covers >99 % of lemniscate energy
FRAME_END    = 256    # animation length = one complete path period
RADIUS_SCALE = 1.8    # Blender units per unit of DFT amplitude
TRAIL_BEVEL  = 0.011  # tube radius for the glowing light-painting trail
RING_BEVEL   = 0.006  # tube radius for the phasor orbit rings
EMISSION_STR = 11.0   # trail emission strength — high enough to trigger EEVEE bloom
RING_STR     = 2.8    # dim ring glow so orbits read without drowning the trail
COL_TRAIL    = (0.05, 0.95, 0.60)  # lime-green — high luminance
COL_RING     = (0.25, 0.55, 1.00)  # periwinkle blue


# ─── 1. PATH: LEMNISCATE OF BERNOULLI ────────────────────────────────────────
def lemniscate(n: int):
    """
    Closed parametric curve  x = cos t / (1 + sin²t),  y = sin t · cos t / (1 + sin²t).

    This is the natural poi figure-eight. Its DFT is sparse: dominant energy
    at k = ±1 (the "figure envelope") and k = ±3 (the crossing correction).
    Most higher modes are essentially zero, so N_CIRCLES = 22 reconstructs it
    almost exactly (relative error < 0.001).
    """
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    d = 1.0 + np.sin(t) ** 2
    return np.cos(t) / d, np.sin(t) * np.cos(t) / d


x_path, y_path = lemniscate(N_SAMPLES)
z_path = x_path + 1j * y_path   # treat 2-D coords as complex plane


# ─── 2. DISCRETE FOURIER TRANSFORM ───────────────────────────────────────────
C = np.fft.fft(z_path)
# fftfreq returns signed integers: [0, 1, …, N/2−1, −N/2, …, −1].
# Positive k → CCW rotation; negative k → CW.
freqs = np.fft.fftfreq(N_SAMPLES, d=1.0 / N_SAMPLES)

idx   = np.argsort(-np.abs(C))[:N_CIRCLES]  # indices of top N_CIRCLES amplitudes
amps  = np.abs(C[idx]) / N_SAMPLES           # |C[k]| / N  (IDFT normalisation)
phases = np.angle(C[idx])                    # arg(C[k]) in radians
k_vals = freqs[idx]                          # signed frequency for each chosen term


# ─── 3. SCENE RESET ──────────────────────────────────────────────────────────
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete()
scene = bpy.context.scene
scene.frame_start, scene.frame_end = 1, FRAME_END


# ─── 4. MATERIAL FACTORY ─────────────────────────────────────────────────────
def emission_mat(name: str, rgb: tuple, strength: float):
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    em  = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Color"].default_value    = (*rgb, 1.0)
    em.inputs["Strength"].default_value = strength
    nt.links.new(em.outputs["Emission"], out.inputs["Surface"])
    return mat

mat_trail = emission_mat("hf_epi_trail", COL_TRAIL, EMISSION_STR)
mat_ring  = emission_mat("hf_epi_ring",  COL_RING,  RING_STR)


# ─── 5. PHASOR CHAIN OF EMPTIES ──────────────────────────────────────────────
# Each Empty is parented to the previous; local X offset = parent's radius.
# The Z rotation of each Empty is a constant-velocity ramp (2 keyframes only).
empties = []
prev    = None

for i, (amp, phase, k) in enumerate(zip(amps, phases, k_vals)):
    r = float(amp) * RADIUS_SCALE

    bpy.ops.object.empty_add(type='PLAIN_AXES', location=(0, 0, 0))
    em = bpy.context.active_object
    em.name = f"Phasor_{i:02d}"
    em.empty_display_size = 0.04

    if prev is not None:
        em.parent = prev
        # Displace by the PARENT's radius so this empty starts at the parent's tip.
        em.location = (float(amps[i - 1]) * RADIUS_SCALE, 0.0, 0.0)

    # Two-keyframe constant rotation — far cheaper than per-frame baking.
    # omega = signed angular velocity in radians/frame.
    omega = 2.0 * math.pi * float(k) / FRAME_END
    if not em.animation_data:
        em.animation_data_create()
    action = bpy.data.actions.new(f"rot_{em.name}")
    em.animation_data.action = action
    fc = action.fcurves.new(data_path="rotation_euler", index=2)
    kp1 = fc.keyframe_points.insert(1,             phase)
    kp2 = fc.keyframe_points.insert(FRAME_END + 1, phase + omega * FRAME_END)
    kp1.interpolation = kp2.interpolation = 'LINEAR'

    # Orbit ring: Bezier circle curve, bevelled to a tube, parented to this Empty
    bpy.ops.curve.primitive_bezier_circle_add(radius=r, location=(0, 0, 0))
    ring_obj = bpy.context.active_object
    ring_obj.name = f"Ring_{i:02d}"
    ring_obj.parent = em
    ring_obj.data.bevel_depth      = RING_BEVEL
    ring_obj.data.bevel_resolution = 3
    ring_obj.data.materials.append(mat_ring)

    empties.append(em)
    prev = em


# ─── 6. TIP EMPTY ────────────────────────────────────────────────────────────
bpy.ops.object.empty_add(type='PLAIN_AXES', location=(0, 0, 0))
tip = bpy.context.active_object
tip.name = "Tip"
tip.parent = empties[-1]
tip.location = (float(amps[-1]) * RADIUS_SCALE, 0.0, 0.0)


# ─── 7. TRAIL VIA DEPSGRAPH EVALUATION ───────────────────────────────────────
# Evaluate the full parent-chain world transform at each frame.
# We must call dg.update() after frame_set() to propagate the FCurve rotations.
bpy.context.view_layer.update()
dg = bpy.context.evaluated_depsgraph_get()
trail_pts = []

for f in range(1, FRAME_END + 1):
    scene.frame_set(f)
    dg.update()
    tip_ev = tip.evaluated_get(dg)
    trail_pts.append(tip_ev.matrix_world.translation.copy())

trail_pts.append(trail_pts[0])   # close the loop


# ─── 8. TRAIL MESH → CURVE ───────────────────────────────────────────────────
me_trail = bpy.data.meshes.new("hf_epi_trail_me")
bm3 = bmesh.new()
prev_v = None
for pt in trail_pts:
    v = bm3.verts.new(Vector(pt))
    if prev_v:
        bm3.edges.new([prev_v, v])
    prev_v = v
bm3.to_mesh(me_trail)
bm3.free()

trail_obj = bpy.data.objects.new("hf_epicycle_trail", me_trail)
bpy.context.collection.objects.link(trail_obj)
bpy.context.view_layer.objects.active = trail_obj
bpy.ops.object.select_all(action='DESELECT')
trail_obj.select_set(True)
bpy.ops.object.convert(target='CURVE')
trail_obj.data.bevel_depth      = TRAIL_BEVEL
trail_obj.data.bevel_resolution = 5
trail_obj.data.materials.append(mat_trail)


# ─── 9. EEVEE NEXT + BLOOM ───────────────────────────────────────────────────
scene.render.engine = 'BLENDER_EEVEE_NEXT'
ev = scene.eevee
ev.use_bloom       = True
ev.bloom_threshold = 0.35
ev.bloom_intensity = 1.4
ev.bloom_radius    = 5.5

world = bpy.data.worlds.new("hf_black_sky")
world.use_nodes = True
bg = world.node_tree.nodes["Background"]
bg.inputs["Color"].default_value    = (0, 0, 0, 1)
bg.inputs["Strength"].default_value = 0.0
scene.world = world

# ─── 10. CAMERA ──────────────────────────────────────────────────────────────
bpy.ops.object.camera_add(location=(0, -4.5, 2.2))
cam = bpy.context.active_object
cam.rotation_euler = (math.radians(70), 0, 0)
cam.data.lens = 42
scene.camera = cam

print(f"Epicycle chain built — {N_CIRCLES} circles, {N_SAMPLES} trail points.")
print(f"Top-4 freqs: {k_vals[:4].astype(int)}   amps: {amps[:4].round(4)}")
